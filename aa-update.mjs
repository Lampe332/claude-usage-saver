// Fetches the Claude model figures from artificialanalysis.ai and rewrites aa-data.md.
// Usage:  node aa-update.mjs
// When a new model generation ships, only FAMILIES needs editing.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const SOURCE = 'https://artificialanalysis.ai/providers/anthropic';
const OUT = join(dirname(fileURLToPath(import.meta.url)), 'aa-data.md');
// [slug part on the website, display name, value for the Agent tool's `model` parameter]
const FAMILIES = [
  ['fable-5-2', 'Fable 5.2', 'fable'],
  ['opus-5-5', 'Opus 5.5', 'opus'],
  ['sonnet-5-5', 'Sonnet 5.5', 'sonnet'],
  ['haiku-5-5', 'Haiku 5.5', 'haiku'],
];
// slug suffix on the website -> effort level ('' is the max variant)
const EFFORTS = [['-low', 'low'], ['-medium', 'medium'], ['-high', 'high'], ['-xhigh', 'xhigh'], ['', 'max']];

const res = await fetch(SOURCE, { headers: { 'User-Agent': 'Mozilla/5.0' } });
if (!res.ok) { console.error(`Fetch failed: HTTP ${res.status}`); process.exit(1); }
const html = await res.text();

// The page ships its data as a Next.js stream inside <script> blocks.
const flat = [...html.matchAll(/self\.__next_f\.push\(\[1,"((?:[^"\\]|\\.)*)"\]\)/g)]
  .map((m) => { try { return JSON.parse(`"${m[1]}"`); } catch { return ''; } })
  .join('');

function objectStart(i) {
  let depth = 0;
  for (let s = i; s >= 0; s--) {
    if (flat[s] === '}') depth++;
    else if (flat[s] === '{') { if (depth === 0) return s; depth--; }
  }
  return -1;
}
function parseObject(s) {
  let depth = 0, inStr = false;
  for (let e = s; e < flat.length; e++) {
    const c = flat[e];
    if (inStr) { if (c === '\\') e++; else if (c === '"') inStr = false; continue; }
    if (c === '"') inStr = true;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return JSON.parse(flat.slice(s, e + 1));
  }
  throw new Error('object not closed');
}

// Each row of the comparison table: { model: {slug, intelligenceIndex, scores}, pricing, performance, features }
const bySlug = {};
for (const m of flat.matchAll(/"costPerTask":/g)) {
  try {
    const o = parseObject(objectStart(objectStart(m.index) - 1));
    if (o.model?.slug && o.pricing && o.performance) bySlug[o.model.slug] ??= o;
  } catch { /* not a table object */ }
}

const rows = [];
for (const [slugPart, label, param] of FAMILIES) {
  for (const [suffix, effort] of EFFORTS) {
    const o = bySlug[`claude-${slugPart}${suffix}`];
    if (!o) continue;
    const sc = o.model.scores ?? {};
    rows.push({
      label, param, effort,
      cost: o.pricing.costPerTask,
      index: o.model.intelligenceIndex,
      code: sc['frontiercode-2-0'], term: sc['terminalbench-4-0'],
      termSci: sc['terminal-bench-science'], auto: sc['automationbench-aa'],
      brief: sc['aa-briefcase'], gdpval: sc['gdpval-aa-normalized'],
      acc: sc['omniscience-accuracy'], nonHall: sc['omniscience-non-hallucination'],
      hle: sc['hle-diamond'], critpt: sc['critpt-v2-hard'],
      lcr: sc['artificial-analysis-long-context-reasoning'], gdpPdf: sc['gdp-pdf'],
      minutes: o.performance.intelligenceIndexTimePerTask / 60,
      speed: o.performance.outputSpeed, wait: o.performance.timeToFirstAnswerToken,
      pIn: o.pricing.price1mInputTokens, pOut: o.pricing.price1mOutputTokens,
      pHit: o.pricing.cacheHitPrice, pWrite: o.pricing.cacheWritePrice,
      ctx: o.features?.contextWindowTokens,
    });
  }
}
if (rows.length < FAMILIES.length * 3) {
  console.error(`Only ${rows.length} rows found – page layout changed or FAMILIES is outdated. aa-data.md left untouched.`);
  process.exit(1);
}

// Dominated = another setting costs no more and is at least as good on index, code and terminal.
const name = (r) => `${r.label} ${r.effort}`;
for (const a of rows) {
  const better = rows
    .filter((b) => b !== a && b.cost <= a.cost && b.index >= a.index && b.code >= a.code && b.term >= a.term
      && (b.cost < a.cost || b.index > a.index || b.code > a.code || b.term > a.term))
    .sort((x, y) => x.cost - y.cost)[0];
  a.dominatedBy = better ? name(better) : '';
}

const n = (x, d = 1) => (x == null ? '–' : Number(x).toFixed(d));
const p = (x) => (x == null ? '–' : (x * 100).toFixed(1));
const byCost = [...rows].sort((a, b) => a.cost - b.cost);
const today = new Date().toISOString().slice(0, 10);

const md = `# Artificial Analysis data: Claude models per effort level

As of: ${today} · Source: ${SOURCE} · generated by \`aa-update.mjs\` (do not edit by hand – regenerate).
Benchmark figures are the work of Artificial Analysis; this file only reformats their published numbers.

## Table 1 – price ladder (cheap → expensive)

- **\`model\` / \`effort\`**: exactly these values go into the Agent call.
- **$/task**: cost in US dollars for an average Intelligence Index task (API prices; on a subscription a measure of relative usage).
- **Index**: Artificial Analysis Intelligence Index, overall score 0–100.
- **Code**: FrontierCode-AA 2.0 – software engineering in real repositories, % solved.
- **Terminal**: Terminal-Bench 4.0 – command line, builds, tools, % solved.
- **Min/task**: duration per index task. **Dominated by**: a setting that costs no more and is at least as good on index, code and terminal.

| Model | \`model\` | \`effort\` | $/task | Index | Code % | Terminal % | Min/task | Dominated by |
|---|---|---|---|---|---|---|---|---|
${byCost.map((r) => `| ${r.label} | ${r.param} | ${r.effort} | ${n(r.cost, 2)} | ${n(r.index)} | ${p(r.code)} | ${p(r.term)} | ${n(r.minutes)} | ${r.dominatedBy} |`).join('\n')}

## Table 2 – individual benchmarks by kind of work

- **Research**: Terminal-Bench-Science 0.1 – multi-step analysis workflows in a terminal, %.
- **Workflows**: AutomationBench-AA – workflows across several apps and services, %.
- **Office (Elo)**: AA-Briefcase v1.1 – knowledge work with documents. **GDPval (Elo)**: real professional tasks.
- **Knowledge**: AA-Omniscience – share of correct facts from memory. **Not invented**: share of cases where the model does not make something up when it does not know.
- **Reasoning**: HLE-Diamond – very hard expert questions, %. **Physics**: CritPt v2 (hard subset), %.
- **Long text**: reasoning over long documents, %. **PDF**: GDP.pdf – documents with tables and figures, %.

| Model | \`effort\` | Research | Workflows | Office | GDPval | Knowledge | Not invented | Reasoning | Physics | Long text | PDF |
|---|---|---|---|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.label} | ${r.effort} | ${p(r.termSci)} | ${p(r.auto)} | ${n(r.brief, 0)} | ${n(r.gdpval, 0)} | ${p(r.acc)} | ${p(r.nonHall)} | ${p(r.hle)} | ${p(r.critpt)} | ${p(r.lcr)} | ${p(r.gdpPdf)} |`).join('\n')}

## Table 3 – prices and speed

Prices in US dollars per 1M tokens. **Cache read** is the price for history that was already read – this is why long runs are expensive: every step re-reads the whole history.

| Model | \`effort\` | Input | Output | Cache read | Cache write | Tokens/s | Wait until answer (s) | Context |
|---|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r.label} | ${r.effort} | ${r.pIn} | ${r.pOut} | ${r.pHit} | ${r.pWrite} | ${n(r.speed, 0)} | ${n(r.wait, 0)} | ${r.ctx ? `${r.ctx / 1000}k` : '–'} |`).join('\n')}
`;

writeFileSync(OUT, md, 'utf8');
console.log(`${rows.length} settings written to ${OUT} (as of ${today})`);
const known = new Set(FAMILIES.map(([s]) => s));
const others = [...new Set(Object.keys(bySlug).map((s) => s.match(/^claude-([a-z]+-\d+(?:-\d+)?)-xhigh$/)?.[1]).filter((s) => s && !known.has(s)))];
if (others.length) console.log(`Note: more models with effort levels on the page, not in FAMILIES: ${others.join(', ')}`);
